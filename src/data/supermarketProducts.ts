export function findProductMatches(query: string, limit = 8): CatalogProduct[] {
  const q = normalizeProduct(query);
  if (!q) return [];
  const scored: { p: CatalogProduct; score: number }[] = [];
  for (const p of SUPERMARKET_PRODUCTS) {
    const name = normalizeProduct(p.n);
    if (name === q) { scored.push({ p, score: 0 }); continue; }
    if (name.startsWith(q)) { scored.push({ p, score: 1 }); continue; }
    if (p.a?.some(a => normalizeProduct(String(a)).includes(q))) { scored.push({ p, score: 2 }); continue; }
    if (name.includes(q)) { scored.push({ p, score: 3 }); continue; }
  }
  return scored.sort((a, b) => a.score - b.score).slice(0, limit).map(s => s.p);
}

export function guessEmoji(name: string): string {
  const n = name.toLowerCase();
  for (const entry of Object.entries(SHOPPING_ICONS)) {
    if (n.includes(entry[0])) return entry[1];
  }
  return '🛒';
}

export function normalizeProduct(s: string): string {
  return s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
}
