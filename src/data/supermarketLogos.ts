export function gotStoreLogo(id: string): boolean {
  if (!id) return false;
  return !!logoFor(id) || id in SUPER_LOGO_FALLBACKS;
}

export const logoFor = (id: string): string | undefined => {
  if (!id) return undefined;
  const clean = id.toLowerCase().trim();
  if (SUPERMARKET_LOGOS[clean]) return SUPERMARKET_LOGOS[clean];
  const normalized = clean
    .replace('md-discount', 'md')
    .replace('-italia', '')
    .replace('iper-', '')
    .replace('-market', '')
    .replace('-supermercati', '')
    .replace(/[^a-z0-9]/g, '');
  if (SUPERMARKET_LOGOS[normalized]) return SUPERMARKET_LOGOS[normalized];
  return undefined;
};

